-- ============================================================================
-- Mess Mates — 003 signup repair
-- Run this once in the Supabase SQL editor (Dashboard → SQL → New query),
-- after 002_hardening.sql. Safe to re-run: everything is idempotent.
--
-- "Database error saving new user" means the profile bootstrap trigger raised,
-- and GoTrue then cancelled the whole sign-up (so Google sign-in bounced back
-- to the login page too). This migration:
--   1. records the real Postgres error in public.signup_errors instead of
--      hiding it behind GoTrue's generic message,
--   2. stops profile bootstrap from ever blocking authentication,
--   3. repairs schema drift on public.profiles, which is what usually makes
--      the insert fail on a project that was migrated incrementally.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Where the real error is recorded
-- ----------------------------------------------------------------------------
create table if not exists public.signup_errors (
  id bigint generated by default as identity primary key,
  user_id uuid,
  email text,
  sqlstate text,
  message text,
  created_at timestamptz not null default now()
);

alter table public.signup_errors enable row level security;
-- No policies on purpose: only the SQL editor / service role can read it.
revoke all on public.signup_errors from anon, authenticated;
grant select on public.signup_errors to service_role;

-- ----------------------------------------------------------------------------
-- 2. Repair public.profiles
-- `create table if not exists` in 001 never adds columns to a table that was
-- created by an earlier revision, so the bootstrap insert could be missing a
-- column or hitting an old NOT NULL. Re-add everything the app expects.
-- ----------------------------------------------------------------------------
alter table public.profiles add column if not exists full_name text;
alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists avatar_url text;
alter table public.profiles add column if not exists is_pro boolean not null default false;
alter table public.profiles add column if not exists xp_points integer not null default 0;
alter table public.profiles add column if not exists avatar_frame text not null default 'ring';
alter table public.profiles add column if not exists frame_unlocked_until timestamptz;
alter table public.profiles add column if not exists created_at timestamptz not null default now();

update public.profiles set full_name = 'Member' where full_name is null;
alter table public.profiles alter column full_name set default 'Member';
alter table public.profiles alter column full_name set not null;

-- ----------------------------------------------------------------------------
-- 3. Profile bootstrap that cannot block sign-up
-- A failed profile insert is recorded and logged, then ignored: the app creates
-- the profile itself after sign-in (see ensureProfile in supabaseBackend.ts).
-- ----------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_name text;
begin
  v_name := coalesce(
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
    nullif(btrim(new.raw_user_meta_data ->> 'name'), ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    'Member'
  );

  begin
    insert into public.profiles (id, full_name, email, avatar_url)
    values (
      new.id,
      v_name,
      new.email,
      nullif(new.raw_user_meta_data ->> 'avatar_url', '')
    )
    on conflict (id) do nothing;
  exception when others then
    declare
      v_message text := sqlerrm;
      v_state text := sqlstate;
    begin
      -- Retry with just the id: most drift is a changed optional column, and a
      -- profile row with the default name still lets the app work.
      begin
        insert into public.profiles (id) values (new.id) on conflict (id) do nothing;
        raise warning 'handle_new_user used the id-only fallback for % (%)', new.id, v_message;
      exception when others then
        begin
          insert into public.signup_errors (user_id, email, sqlstate, message)
          values (new.id, new.email, v_state, v_message);
        exception when others then
          null; -- logging must never raise either
        end;
        raise warning 'handle_new_user failed for %: % (%)', new.id, v_message, v_state;
      end;
    end;
  end;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

grant execute on function public.handle_new_user() to public;

-- Show any other trigger on auth.users, in case the failure came from one of
-- them rather than from ours. The SQL editor prints these notices.
do $$
declare
  r record;
begin
  for r in
    select t.tgname, p.proname
      from pg_trigger t
      join pg_class c on c.oid = t.tgrelid
      join pg_proc p on p.oid = t.tgfoid
     where c.oid = 'auth.users'::regclass
       and not t.tgisinternal
  loop
    raise notice 'trigger on auth.users: % -> %()', r.tgname, r.proname;
  end loop;
end;
$$;
