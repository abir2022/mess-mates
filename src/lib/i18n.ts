export const messageKeys = Object.keys(en) as MessageKey[]

const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, bn }
const listeners = new Set<() => void>()

function readLang(): Lang {
  try {
    if (typeof window === 'undefined' || !window.localStorage) return 'en'
    return window.localStorage.getItem(STORAGE_KEY) === 'bn' ? 'bn' : 'en'
  } catch {
    return 'en'
  }
}

let current: Lang = readLang()

export function getLang(): Lang {
  return current
}

export function setLang(lang: Lang): void {
  current = lang
  try {
    if (typeof window !== 'undefined') {
      window.localStorage?.setItem(STORAGE_KEY, lang)
      document.documentElement.lang = lang
    }
  } catch {
    // Private mode without storage still gets the in-memory switch.
  }
  listeners.forEach((listener) => {
    try {
      listener()
    } catch {
      // A broken subscriber must not block the language switch.
    }
  })
}

export function toggleLang(): Lang {
  const next: Lang = current === 'en' ? 'bn' : 'en'
  setLang(next)
  return next
}

export function translate(
  key: MessageKey,
  vars?: Record<string, string | number>,
  lang: Lang = current,
): string {
  const template = dictionaries[lang][key] ?? en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  )
}

/** The translator for the active language. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  return translate(key, vars)
}

export function useI18n(): {
  lang: Lang
  setLang: (lang: Lang) => void
  toggle: () => void
  t: (key: MessageKey, vars?: Record<string, string | number>) => string
} {
  const [lang, setLangState] = useState<Lang>(current)

  // Stored language has to mark the document too, or the Bangla font and
  // line-height never apply on a fresh load.
  useEffect(() => {
    if (typeof document !== 'undefined') document.documentElement.lang = lang
  }, [lang])

  useEffect(() => {
    setLangState(current)
    const onChange = () => setLangState(current)
    listeners.add(onChange)
    window.addEventListener(CHANGE_EVENT, onChange)
    return () => {
      listeners.delete(onChange)
      window.removeEventListener(CHANGE_EVENT, onChange)
    }
  }, [])

  const change = useCallback((next: Lang) => {
    setLang(next)
    window.dispatchEvent(new Event(CHANGE_EVENT))
  }, [])

  const flip = useCallback(() => {
    toggleLang()
    window.dispatchEvent(new Event(CHANGE_EVENT))
  }, [])

  const translator = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => translate(key, vars, lang),
    [lang],
  )

  return { lang, setLang: change, toggle: flip, t: translator }
}
